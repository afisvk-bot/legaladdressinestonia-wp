const { chromium, devices } = require('playwright'); const fs = require('fs');
const B = 'https://staging.dragonslots-gr.gr';
const HIDE = '#lae-cookie-consent,[class*="lae-cookie"],[class*="cookie-consent"],[class*="cky-"]{display:none!important}';
(async () => {
  const out = process.argv[2]; const b = await chromium.launch(); const rep = {};
  let ctx = await b.newContext({ viewport: { width: 1440, height: 900 } }); let p = await ctx.newPage();
  p.on('console', m => { if (m.type() === 'error') (rep.console = rep.console || []).push(m.text().slice(0, 200)); });
  await p.goto(B + '/', { waitUntil: 'networkidle' }); await p.addStyleTag({ content: HIDE });
  await p.screenshot({ path: out + '/d-header.png', clip: { x: 0, y: 0, width: 1440, height: 110 } });
  for (const w of [1399, 1280, 1200, 1024, 992]) { await p.setViewportSize({ width: w, height: 900 }); await p.waitForTimeout(300); await p.screenshot({ path: out + `/d-header-${w}.png`, clip: { x: 0, y: 0, width: w, height: 110 } }); }
  await p.setViewportSize({ width: 1440, height: 900 });
  await p.locator('footer .lai-fc').scrollIntoViewIfNeeded(); await p.waitForTimeout(500);
  await p.locator('footer').first().screenshot({ path: out + '/d-footer.png' });
  await p.evaluate(() => window.scrollTo(0, 0));
  await p.click('.lai-hc__book'); await p.waitForTimeout(600);
  rep.modalVisible = await p.isVisible('#book-a-call');
  rep.fixed = await p.evaluate(() => [...document.querySelectorAll('body *')].filter(e => { const s = getComputedStyle(e); if (s.position !== 'fixed') return false; const r = e.getBoundingClientRect(); return r.right > innerWidth - 150 && r.bottom > innerHeight - 200 && r.width > 0; }).map(e => e.tagName + '#' + e.id + '.' + String(e.className).slice(0, 80) + ' vis=' + getComputedStyle(e).visibility).slice(0, 12));
  await p.screenshot({ path: out + '/d-modal.png' });
  await p.click('.lcf .wpcf7-radio >> text=Telegram'); await p.waitForTimeout(300);
  rep.afterTg = await p.evaluate(() => [document.querySelector('.lcf-contact-label').textContent, document.querySelector('#lcf-contact').placeholder]);
  await p.click('.lcf input.lcf__btn'); await p.waitForTimeout(2500);
  rep.emptySubmit = await p.evaluate(() => ({ resp: (document.querySelector('.lcf .wpcf7-response-output') || {}).innerText, tips: [...document.querySelectorAll('.lcf .wpcf7-not-valid-tip')].map(x => x.innerText) }));
  await p.screenshot({ path: out + '/d-modal-errors.png' });
  await p.click('.lcf .wpcf7-radio >> text=Email');
  await p.fill('#lcf-name', 'Test'); await p.fill('#lcf-contact', 'not-an-email'); await p.waitForTimeout(3500);
  await p.click('.lcf input.lcf__btn'); await p.waitForTimeout(2500);
  rep.badEmail = await p.evaluate(() => [...document.querySelectorAll('.lcf .wpcf7-not-valid-tip')].map(x => x.innerText));
  await p.keyboard.press('Escape'); rep.closedByEsc = !(await p.isVisible('#book-a-call'));
  await ctx.close();
  // RU, mobile: real submission
  ctx = await b.newContext({ ...devices['iPhone 13'] }); p = await ctx.newPage();
  await p.goto(B + '/ru/', { waitUntil: 'networkidle' }); await p.addStyleTag({ content: HIDE });
  await p.screenshot({ path: out + '/m-header.png', clip: { x: 0, y: 0, width: 390, height: 100 } });
  await p.click('.mm-toggle'); await p.waitForTimeout(900);
  await p.evaluate(() => { const m = document.querySelector('.lai-mmc'); if (m) m.scrollIntoView({ block: 'end' }); }); await p.waitForTimeout(400);
  await p.screenshot({ path: out + '/m-menu.png' });
  await p.click('.mm-toggle'); await p.waitForTimeout(600);
  await p.locator('footer .lai-fc').scrollIntoViewIfNeeded(); await p.waitForTimeout(400);
  await p.locator('footer .lai-fc').screenshot({ path: out + '/m-footer.png' });
  await p.click('footer .lai-fc__book'); await p.waitForTimeout(700);
  await p.screenshot({ path: out + '/m-modal.png' });
  fs.writeFileSync(out + '/rep.json', JSON.stringify(rep, null, 1)); await b.close();
})();
